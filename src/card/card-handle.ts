import { LitElement, css, html } from 'lit';
import { property } from 'lit/decorators.js';
import { ifDefined } from 'lit/directives/if-defined.js';
import { stateLayer } from '../internal/state-layer.js';
import { iconGrip } from '../internal/icons.js';

/**
 * The drag handle of a reorderable card, first in the header. NAME PROVISIONAL.
 *
 * A real `<button>` at least 24 by 24px, named "Reorder {title}" (the card
 * writes the label). It shows a grab cursor and a tint on hover. Dragging is
 * done by the list's pointer controller; on touch it starts with a press and
 * hold, so scrolling still works. A drag is never the only way to move a card:
 * the list adds Move items to the card's overflow menu.
 *
 * If the card has no overflow menu and moving is its only action, the handle
 * is the menu button itself (`menu`): the list puts a menu in it, named
 * "Reorder {title}". A card never has both.
 *
 * @tag prism-card-handle
 * @slot - The move menu (menu mode only; generated by the list).
 * @csspart base - The button (not rendered in menu mode).
 */
export class PrismCardHandle extends LitElement {
  static override shadowRootOptions: ShadowRootInit = {
    ...LitElement.shadowRootOptions,
    delegatesFocus: true,
  };

  static override styles = [
    css`
      :host {
        display: inline-block;
        inline-size: 2rem;
        block-size: 2rem;
        cursor: grab;
        touch-action: manipulation;
        user-select: none;
      }
      :host([menu]) {
        inline-size: auto;
        block-size: auto;
      }
      :host([hidden]) {
        display: none;
      }
      [part='base'] {
        all: unset;
        box-sizing: border-box;
        display: inline-flex;
        align-items: center;
        justify-content: center;
        inline-size: 100%;
        block-size: 100%;
        min-inline-size: 1.5rem;
        min-block-size: 1.5rem;
        border: var(--prism-border-width, 1px) solid transparent;
        border-radius: var(--prism-radius-5, 5px);
        cursor: inherit;
      }
      [part='base']:focus-visible {
        outline: revert;
      }
      [part='base'] svg {
        inline-size: 1rem;
        block-size: 1rem;
        pointer-events: none;
      }
    `,
    stateLayer("[part='base']"),
  ];

  /** The accessible name, "Reorder {title}". Set by the card. */
  @property() label = '';
  /** @internal The handle is the move menu's button (card has no overflow menu). */
  @property({ type: Boolean, reflect: true }) menu = false;
  /** @internal A short hint for keyboard users; set by the card. */
  @property() hint = '';

  /** Focuses the control a keyboard user pressed (the button or the menu button). */
  focusControl(): void {
    const own = this.renderRoot.querySelector<HTMLElement>('[part="base"]');
    if (own) return own.focus();
    const menu = this.querySelector('prism-menu');
    menu?.shadowRoot?.querySelector<HTMLElement>('[part="trigger"]')?.focus();
  }

  override render() {
    if (this.menu) return html`<slot></slot>`;
    return html`<button
      part="base"
      type="button"
      aria-label=${this.label || 'Reorder'}
      aria-description=${ifDefined(this.hint || undefined)}
    >
      ${iconGrip()}
    </button>`;
  }
}
